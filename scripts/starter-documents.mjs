/**
 * Writes `src/starter/documents.generated.ts`: every bundle of `content/`, as
 * imports of its Markdown files, for the starter Mallok's first-run wizard
 * offers (`src/starter/index.ts`).
 *
 *   node scripts/starter-documents.mjs
 *
 * Generated rather than written by hand because there are a hundred and more
 * files, and a list kept by hand drifts from the directory it lists:
 * `test/starter.test.ts` fails when the file is not what this writes.
 *
 * A bundle is a directory of `content/<kind>/`; `index.md` is the default
 * language, whose slug is the directory's name, and `index.<locale>.md` a
 * translation, whose slug is in its front matter.
 */

import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const CONTENT = join(ROOT, 'content');
const OUTPUT = join(ROOT, 'src', 'starter', 'documents.generated.ts');

/** The value of a top-level key in a file's front matter, or null. */
function frontMatterValue(text, key) {
  const end = text.indexOf('\n---', 3);
  const head = text.startsWith('---') && end !== -1 ? text.slice(0, end) : '';
  const line = head
    .split('\n')
    .find((candidate) => candidate.startsWith(`${key}:`));
  if (line === undefined) {
    return null;
  }
  return line
    .slice(key.length + 1)
    .trim()
    .replace(/^"(.*)"$/, '$1');
}

/** The module's text, from what is in `content/` now. */
export async function renderStarterDocuments() {
  const imports = [];
  const bundles = [];
  for (const kind of (await readdir(CONTENT)).sort()) {
    const kindDir = join(CONTENT, kind);
    const dirs = (await readdir(kindDir, { withFileTypes: true }))
      .filter((entry) => entry.isDirectory())
      .map((entry) => entry.name)
      .sort();
    for (const dir of dirs) {
      const files = (await readdir(join(kindDir, dir)))
        .filter((name) =>
          /^index(\.[a-z]{2}(-[A-Za-z]{2,4})?)?\.md$/.test(name),
        )
        .sort();
      if (!files.includes('index.md')) {
        continue;
      }
      const languages = [];
      for (const file of files) {
        const name = `d${imports.length}`;
        imports.push(
          `import ${name} from '../../content/${kind}/${dir}/${file}';`,
        );
        const locale = /^index\.(.+)\.md$/.exec(file)?.[1] ?? null;
        const slug =
          locale === null
            ? dir
            : frontMatterValue(
                await readFile(join(kindDir, dir, file), 'utf8'),
                'slug',
              );
        if (slug === null) {
          throw new Error(`content/${kind}/${dir}/${file} names no slug`);
        }
        languages.push({ locale, slug, name });
      }
      bundles.push({ kind, languages });
    }
  }

  const entry = (bundle) => {
    const own = bundle.languages.find((language) => language.locale === null);
    const translations = bundle.languages.filter(
      (language) => language.locale !== null,
    );
    return [
      '  {',
      `    kind: '${bundle.kind}',`,
      `    slug: '${own.slug}',`,
      `    markdown: ${own.name},`,
      '    translations: {',
      // Written as Biome formats it, so that the file passes the lint as
      // it is generated.
      ...translations.flatMap((language) => [
        `      ${/^[a-z]+$/.test(language.locale) ? language.locale : `'${language.locale}'`}: {`,
        `        slug: '${language.slug}',`,
        `        markdown: ${language.name},`,
        '      },',
      ]),
      '    },',
      '  },',
    ].join('\n');
  };

  return [
    '// Generated by scripts/starter-documents.mjs from content/. Do not edit:',
    '// run `node scripts/starter-documents.mjs` after changing content/.',
    '',
    ...imports,
    '',
    'export interface SampleBundle {',
    '  readonly kind: string;',
    '  readonly slug: string;',
    '  readonly markdown: string;',
    '  readonly translations: Readonly<',
    '    Record<string, { readonly slug: string; readonly markdown: string }>',
    '  >;',
    '}',
    '',
    'export const SAMPLE_BUNDLES: readonly SampleBundle[] = [',
    ...bundles.map(entry),
    '];',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(OUTPUT, await renderStarterDocuments());
  console.log(`Wrote ${OUTPUT}`);
}
